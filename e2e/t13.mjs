import { open } from './lib.mjs';
import assert from 'node:assert/strict';
const { browser, page, errors } = await open();
await page.addInitScript(() => {
  if (localStorage.getItem('seeded')) return;
  localStorage.setItem('seeded', '1'); localStorage.setItem('cfg:tour', '1');
  localStorage.setItem('day:2026-10-07', JSON.stringify([{ id: 'b1aaaaaaaa', s: 540, e: 600, t: 'Estudiar', c: 'estudio', n: '', d: false }]));
});
await page.goto('http://localhost:5199/'); await page.waitForSelector('#app:not([hidden])'); await page.clock.runFor(1500);
const settle = () => page.clock.runFor(400);
assert.match(await page.locator('#inboxBtn').textContent(), /^\s*Sin hora\s*$/);
await page.click('#inboxBtn'); await settle();
assert.equal(await page.locator('.ib-empty').count(), 1);
await page.fill('#inboxNew', 'Llamar al banco'); await page.click('#inboxAdd'); await settle();
await page.fill('#inboxNew', 'Comprar regalo'); await page.press('#inboxNew', 'Enter'); await settle();
assert.equal(await page.locator('.ib-item').count(), 2); console.log('ok añadir 2');
await page.screenshot({ path: 'inbox-list.png' });
await page.locator('.ib-main', { hasText: 'Llamar' }).click(); await settle();
await page.fill('#ibN', 'Pedir cita'); await page.selectOption('#ibM', '45');
await page.click('#ibC .chip:first-child'); await page.click('#ibSave'); await settle();
assert.match(await page.locator('.ib-item').first().textContent(), /45 min/); console.log('ok editar');
await page.locator('.ib-main', { hasText: 'Llamar' }).click(); await settle();
await page.click('#ibSet'); await settle();
assert.equal(await page.locator('#sheetEdit').evaluate(e => e.classList.contains('open') || getComputedStyle(e).visibility !== 'hidden'), true);
assert.equal(await page.inputValue('#fT'), 'Llamar al banco');
console.log('hora propuesta', await page.inputValue('#fS'), await page.inputValue('#fE'));
await page.click('#saveBtn'); await settle();
assert.match(await page.locator('#toastMsg').textContent(), /horario/);
assert.equal(await page.locator('.item').count(), 2); console.log('ok pasa al horario');
assert.match(await page.locator('#inboxBtn').textContent(), /· 1/);
await page.click('#toastAct'); await settle();
assert.equal(await page.locator('.item').count(), 1);
assert.match(await page.locator('#inboxBtn').textContent(), /· 2/); console.log('ok deshacer');
await page.click('#inboxBtn'); await settle();
await page.locator('.ib-item .ck').first().click(); await settle();
assert.equal(await page.locator('.ib-item').count(), 1); console.log('ok completar');
console.log('errores:', errors.length ? errors : 'ninguno');
await browser.close();
